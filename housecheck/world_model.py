"""Meterless World Model engine, implemented in Python for HouseCheck.

Follows the Meterless World Model specification and its reference
implementation (github.com/Meterless/Meterless/tree/main/engines/world-model,
Apache-2.0) and passes a Python port of its conformance suite
(tests/test_world_model_conformance.py):

* stable hash IDs, byte-identical to the reference: `ent_` + the first 16 hex
  of sha256(`type:normalizeName(name)`), with the reference's normalisation
  (NFKD, strip combining marks, strip zero-width characters, lowercase,
  collapse whitespace). Checked against vectors generated by the reference
  itself (tests/fixtures/meterless_reference_vectors.json);
* merge banding at the reference's boundaries (`decide`): 0.85 auto-merge,
  0.82 review, below that a new entity;
* idempotent ingest: an observation's ID is a hash of its content, so
  re-ingesting the same data changes nothing (`changed` is False and the
  canonical state shape is identical);
* no provenance, no write: every observation needs a source, and anything that
  came through Zetaris needs the SQL that produced it;
* bitemporal relationships: a superseding edge closes the open one, and
  point-in-time queries respect validity (`neighbors_of(..., at=...)`);
* an append-only audit log with a strictly increasing sequence;
* derived, rebuildable views: `current_facts` (what each source says is true
  now) and `conflicts` (attributes where sources disagree).

The World Model is the one shared record that the Researcher writes and the
Critic and Reporter read, so they can never work from different numbers.
"""

from __future__ import annotations

import hashlib
import json
import re
import sqlite3
import time
import unicodedata
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Iterable


class ProvenanceError(ValueError):
    """A write without provenance. The spec's rule: no provenance, no write."""


# ---------------------------------------------------------------- stable IDs (spec section 3; reference stableIds.ts)

_COMBINING = re.compile("[̀-ͯ]")
_ZERO_WIDTH = re.compile("[​-‍﻿]")
_SPACE = re.compile(r"\s+")


def normalize_name(name: str) -> str:
    """NFKD -> strip combining marks -> strip zero-width chars -> lowercase -> collapse whitespace -> trim.

    Same steps, in the same order, as the reference `normalizeName`.
    """
    s = unicodedata.normalize("NFKD", name)
    s = _COMBINING.sub("", s)
    s = _ZERO_WIDTH.sub("", s)
    s = s.lower()
    return _SPACE.sub(" ", s).strip()


def entity_id_from_name(type_: str, name: str) -> str:
    """Name-keyed entity: ent_<first 16 hex of sha256(`type:normalizeName(name)`)> (reference argument order)."""
    return "ent_" + hashlib.sha256(f"{type_}:{normalize_name(name)}".encode("utf-8")).hexdigest()[:16]


def stable_entity_id(name: str, type_: str) -> str:
    """HouseCheck's original argument order; same result as entity_id_from_name."""
    return entity_id_from_name(type_, name)


def decide(similarity: float, auto_merge_at: float = 0.85, review_lower: float = 0.82) -> str:
    """Entity-resolution banding (reference resolve.ts): boundary values merge or queue."""
    if similarity >= auto_merge_at:
        return "auto-merge"
    if similarity >= review_lower:
        return "review"
    return "new"


def canonical_json(value: Any) -> str:
    """Deterministic JSON: sorted keys, no whitespace (the reference's canonicalJson)."""
    return json.dumps(value, sort_keys=True, separators=(",", ":"), default=str, ensure_ascii=False)


def _hash(*parts: Any) -> str:
    return hashlib.sha256(json.dumps(parts, sort_keys=True, default=str).encode("utf-8")).hexdigest()[:16]


# ---------------------------------------------------------------- canonical records

@dataclass
class Observation:
    """One fact about one entity from one source. The unit of ingest."""

    entity_type: str
    entity_name: str
    attribute: str
    value: Any
    source: str  # e.g. "police.uk", "postcodes.io", "FSA food hygiene"
    via: str  # "zetaris" | "sample" | "derived"
    sql: str = ""
    fetched_at: float = field(default_factory=time.time)
    note: str = ""

    @property
    def entity_id(self) -> str:
        return entity_id_from_name(self.entity_type, self.entity_name)

    @property
    def id(self) -> str:
        # Content hash: same entity + attribute + value + source + query = same observation.
        # The query is part of identity so provenance always points at the SQL that produced the value.
        return "obs_" + _hash(self.entity_id, self.attribute, self.value, self.source, self.sql)


@dataclass
class Edge:
    from_name: str
    from_type: str
    type: str
    to_name: str
    to_type: str
    source: str
    valid_from: str = ""  # ISO time the relationship starts; "" = since records began

    @property
    def id(self) -> str:
        # Reference relationshipId: hash(from | type | to | context | validFrom). Re-adding the same edge is a no-op.
        f, t = entity_id_from_name(self.from_type, self.from_name), entity_id_from_name(self.to_type, self.to_name)
        return "rel_" + hashlib.sha256(f"{f}|{self.type}|{t}||{self.valid_from}".encode("utf-8")).hexdigest()[:16]


SCHEMA = """
CREATE TABLE IF NOT EXISTS entities (
  id TEXT PRIMARY KEY, type TEXT NOT NULL, name TEXT NOT NULL,
  mention_count INTEGER NOT NULL DEFAULT 0, first_seen_at REAL, last_seen_at REAL,
  state TEXT NOT NULL DEFAULT 'emerging'
);
CREATE TABLE IF NOT EXISTS observations (
  id TEXT PRIMARY KEY, entity_id TEXT NOT NULL REFERENCES entities(id),
  attribute TEXT NOT NULL, value_json TEXT NOT NULL,
  source TEXT NOT NULL, via TEXT NOT NULL, sql TEXT, fetched_at REAL NOT NULL, note TEXT
);
CREATE INDEX IF NOT EXISTS obs_entity_attr ON observations(entity_id, attribute);
CREATE TABLE IF NOT EXISTS edges (
  id TEXT PRIMARY KEY, from_id TEXT NOT NULL, type TEXT NOT NULL, to_id TEXT NOT NULL, source TEXT NOT NULL,
  valid_from TEXT NOT NULL DEFAULT '', valid_to TEXT
);
CREATE TABLE IF NOT EXISTS run_observations (
  run_id TEXT NOT NULL, observation_id TEXT NOT NULL, PRIMARY KEY (run_id, observation_id)
);
CREATE TABLE IF NOT EXISTS audit (
  seq INTEGER PRIMARY KEY AUTOINCREMENT, at REAL NOT NULL, op TEXT NOT NULL, target TEXT NOT NULL, detail TEXT
);
"""


class WorldModel:
    def __init__(self, path: Path | str = ":memory:"):
        if path != ":memory:":
            Path(path).parent.mkdir(parents=True, exist_ok=True)
        self.db = sqlite3.connect(str(path), check_same_thread=False)
        self.db.row_factory = sqlite3.Row
        self._migrate()
        self.db.executescript(SCHEMA)

    def _migrate(self) -> None:
        """Stores from before bitemporal edges: edges are derived from observations, so rebuild that table."""
        cols = {r[1] for r in self.db.execute("PRAGMA table_info(edges)").fetchall()}
        if cols and "valid_from" not in cols:
            self.db.execute("DROP TABLE edges")

    # ------------------------------------------------------------ audit

    def _audit(self, op: str, target: str, detail: str = "") -> None:
        self.db.execute("INSERT INTO audit (at, op, target, detail) VALUES (?,?,?,?)", (time.time(), op, target, detail))

    def audit(self) -> list[dict[str, Any]]:
        return [dict(r) for r in self.db.execute("SELECT * FROM audit ORDER BY seq").fetchall()]

    # ------------------------------------------------------------ ingest (spec section 5, per-observation path)

    def ingest(self, observations: Iterable[Observation], edges: Iterable[Edge] = (), run_id: str = "") -> dict[str, Any]:
        """extract -> normalize -> resolve -> validate -> append -> project. Safe to re-run."""
        report: dict[str, Any] = {"observations_new": 0, "observations_seen": 0, "entities": 0, "edges": 0, "changed": False}
        now = time.time()
        observations, edges = list(observations), list(edges)
        for ob in observations:  # validate everything before writing anything
            self._validate(ob)
        for e in edges:
            if not e.source:
                raise ProvenanceError(f"relationship {e.type} has no source")
        with self.db:
            touched: set[str] = set()
            for ob in observations:
                eid = ob.entity_id
                report["changed"] |= self._upsert_entity(eid, ob.entity_type, ob.entity_name, now)
                touched.add(eid)
                cur = self.db.execute(
                    "INSERT OR IGNORE INTO observations (id, entity_id, attribute, value_json, source, via, sql, fetched_at, note) VALUES (?,?,?,?,?,?,?,?,?)",
                    (ob.id, eid, ob.attribute, json.dumps(ob.value, sort_keys=True, default=str), ob.source, ob.via, ob.sql, ob.fetched_at, ob.note),
                )
                if cur.rowcount:
                    report["observations_new"] += 1
                    report["changed"] = True
                    self._audit("observe", ob.id, f"{eid}.{ob.attribute} from {ob.source} via {ob.via}")
                else:
                    report["observations_seen"] += 1
                if run_id:
                    self.db.execute("INSERT OR IGNORE INTO run_observations VALUES (?,?)", (run_id, ob.id))
            for e in edges:
                if self._relate(e, now):
                    report["edges"] += 1
                    report["changed"] = True
                touched.update({entity_id_from_name(e.from_type, e.from_name), entity_id_from_name(e.to_type, e.to_name)})
            # rebuild aggregates for touched entities (spec step 9)
            for eid in touched:
                n = self.db.execute("SELECT COUNT(*) FROM observations WHERE entity_id=?", (eid,)).fetchone()[0]
                self.db.execute(
                    "UPDATE entities SET mention_count=?, state=CASE WHEN ?>0 THEN 'active' ELSE state END WHERE id=?",
                    (n, n, eid),
                )
            report["entities"] = len(touched)
        return report

    def relate(self, edge: Edge) -> bool:
        """Add one relationship (closing the open one it supersedes). Returns True if anything changed."""
        if not edge.source:
            raise ProvenanceError(f"relationship {edge.type} has no source")
        with self.db:
            return self._relate(edge, time.time())

    def _relate(self, e: Edge, now: float) -> bool:
        fid, tid = entity_id_from_name(e.from_type, e.from_name), entity_id_from_name(e.to_type, e.to_name)
        changed = self._upsert_entity(fid, e.from_type, e.from_name, now)
        changed |= self._upsert_entity(tid, e.to_type, e.to_name, now)
        cur = self.db.execute(
            "INSERT OR IGNORE INTO edges (id, from_id, type, to_id, source, valid_from, valid_to) VALUES (?,?,?,?,?,?,NULL)",
            (e.id, fid, e.type, tid, e.source, e.valid_from),
        )
        if not cur.rowcount:
            return changed
        self._audit("relate", e.id, f"{fid} -{e.type}-> {tid} from {e.valid_from or 'start'}")
        # Bitemporal supersede: an open edge of the same type from the same entity to a different target
        # that started earlier is closed at the new edge's start.
        old = self.db.execute(
            "SELECT id FROM edges WHERE from_id=? AND type=? AND to_id<>? AND valid_to IS NULL AND valid_from<=?",
            (fid, e.type, tid, e.valid_from),
        ).fetchall()
        for r in old:
            self.db.execute("UPDATE edges SET valid_to=? WHERE id=?", (e.valid_from, r["id"]))
            self._audit("close", r["id"], f"superseded by {e.id} at {e.valid_from}")
        return True

    @staticmethod
    def _validate(ob: Observation) -> None:
        if not ob.entity_name or not ob.attribute:
            raise ValueError(f"observation missing entity or attribute: {ob}")
        if not ob.source:
            raise ProvenanceError(f"observation {ob.attribute} about {ob.entity_name} has no source")
        if ob.via not in {"zetaris", "sample", "derived"}:
            raise ProvenanceError(f"unknown provenance path {ob.via!r}")
        if ob.via == "zetaris" and not ob.sql:
            raise ProvenanceError(f"Zetaris observation {ob.attribute} has no SQL provenance")

    def _upsert_entity(self, eid: str, type_: str, name: str, now: float) -> bool:
        cur = self.db.execute(
            "INSERT OR IGNORE INTO entities (id, type, name, first_seen_at, last_seen_at) VALUES (?,?,?,?,?)",
            (eid, type_, name, now, now),
        )
        if cur.rowcount:
            self._audit("entity", eid, f"{type_}:{name}")
            return True
        self.db.execute("UPDATE entities SET last_seen_at=? WHERE id=?", (now, eid))
        return False

    # ------------------------------------------------------------ read surface (spec section 9)

    def current_facts(self, entity_name: str, entity_type: str = "address") -> dict[str, list[dict[str, Any]]]:
        """Latest value per (attribute, source): what each source says is true now."""
        eid = entity_id_from_name(entity_type, entity_name)
        rows = self.db.execute(
            "SELECT o.* FROM observations o JOIN ("
            "  SELECT attribute, source, MAX(fetched_at) AS t FROM observations WHERE entity_id=? GROUP BY attribute, source"
            ") latest ON o.attribute=latest.attribute AND o.source=latest.source AND o.fetched_at=latest.t "
            "WHERE o.entity_id=? ORDER BY o.attribute, o.source",
            (eid, eid),
        ).fetchall()
        out: dict[str, list[dict[str, Any]]] = {}
        for r in rows:
            out.setdefault(r["attribute"], []).append(_row(r))
        return out

    def fact(self, observation_id: str) -> dict[str, Any] | None:
        r = self.db.execute(
            "SELECT o.*, e.name AS entity_name FROM observations o JOIN entities e ON e.id=o.entity_id WHERE o.id=?", (observation_id,)
        ).fetchone()
        return _row(r) | {"entity_name": r["entity_name"]} if r else None

    def conflicts(self, entity_name: str, entity_type: str = "address") -> list[dict[str, Any]]:
        """Attributes where two sources currently disagree (compared after normalisation)."""
        out = []
        for attribute, facts in self.current_facts(entity_name, entity_type).items():
            values = {normalize_name(str(f["value"])) for f in facts}
            if len(facts) > 1 and len(values) > 1:
                out.append({"attribute": attribute, "facts": facts})
        return out

    def neighbors_of(self, entity_name: str, entity_type: str = "address", via: str | None = None, at: str | None = None) -> list[dict[str, str]]:
        """Related entities. Without `at`: open edges only. With `at` (ISO time): edges valid at that moment."""
        eid = entity_id_from_name(entity_type, entity_name)
        sql = ("SELECT ed.type, e.id, e.type AS to_type, e.name AS to_name, ed.source, ed.valid_from, ed.valid_to "
               "FROM edges ed JOIN entities e ON e.id=ed.to_id WHERE ed.from_id=?")
        args: list[Any] = [eid]
        if via:
            sql += " AND ed.type=?"
            args.append(via)
        if at is None:
            sql += " AND ed.valid_to IS NULL"
        else:
            sql += " AND ed.valid_from<=? AND (ed.valid_to IS NULL OR ed.valid_to>?)"
            args += [at, at]
        return [dict(r) for r in self.db.execute(sql, args).fetchall()]

    # Kept for callers written before neighbors_of existed.
    def neighbours(self, entity_name: str, entity_type: str = "address") -> list[dict[str, str]]:
        return self.neighbors_of(entity_name, entity_type)

    def snapshot(self) -> dict[str, Any]:
        """Whole-world dump without clock fields, used by the idempotency check."""
        return {
            "observations": [dict(r) for r in self.db.execute(
                "SELECT id, entity_id, attribute, value_json, source, via, sql, note FROM observations ORDER BY id").fetchall()],
            "edges": [dict(r) for r in self.db.execute("SELECT * FROM edges ORDER BY id").fetchall()],
            "entities": [dict(r) for r in self.db.execute("SELECT id, type, name, mention_count, state FROM entities ORDER BY id")],
        }

    def state_shape_canonical(self) -> str:
        """The reference's stateShapeCanonical: one deterministic string for the whole world."""
        return canonical_json(self.snapshot())


def _row(r: sqlite3.Row) -> dict[str, Any]:
    return {
        "id": r["id"],
        "attribute": r["attribute"],
        "value": json.loads(r["value_json"]),
        "source": r["source"],
        "via": r["via"],
        "sql": r["sql"],
        "fetched_at": r["fetched_at"],
        "note": r["note"],
    }
